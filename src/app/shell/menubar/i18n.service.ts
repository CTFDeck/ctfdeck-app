@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly STORAGE_KEY = 'ctfdeck_lang';

  readonly currentLang = signal<SupportedLang>(this.loadInitialLang());

  private loadInitialLang(): SupportedLang {
    const stored = localStorage.getItem(this.STORAGE_KEY) as SupportedLang | null;
    if (stored && ['fr', 'en', 'es'].includes(stored)) return stored;
    const browser = navigator.language.slice(0, 2) as SupportedLang;
    return ['fr', 'en', 'es'].includes(browser) ? browser : 'en';
  }

  setLang(lang: SupportedLang): void {
    this.currentLang.set(lang);
    localStorage.setItem(this.STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  }

  translate(key: string): string {
    return translations[this.currentLang()][key] ?? translations['en'][key] ?? key;
  }
}
